"""Give the play screen (B3) the map's names as an inline layer, as every other map screen has (T-031).

The page drew the shared overlay as one <img>, names included, so a name a panel or the screen edge cut stayed on screen
cut (Benghazi under the alert, a piece of Tehran in the top corner). This takes the label layer that
design/screen4/A/_build/make_overlay.py builds from the shared overlay (city names beside their dots, tools/city_labels.py)
into this page, draws the overlay's shapes from ../../screen4/A/map_overlay_cairo.svg (the same shapes byte for byte,
no names) in the map and in the frosted glass, and adds cutLabels(): after the map is placed, a name (a city: its dot and
name together) whose halo a panel edge would cut (2 pt margin) or that the screen edge or the side inset would slice is
hidden; one fully under a panel stays under its glass. Idempotent.
Usage: python3 -I labels.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAGE = HERE.parent / 'index.html'
A = (HERE.parents[2] / 'screen4/A/index.html').read_text(encoding='utf-8')
BEGIN, END = '<!-- map labels: generated by _build/make_overlay.py from the D1 overlay -->', '<!-- /map labels -->'
block = A[A.index(BEGIN):A.index(END) + len(END)]
t = PAGE.read_text(encoding='utf-8')
MB, ME = '<!-- map labels (T-031): the shared label layer, from screen 4A; made by _build/labels.py -->', '<!-- /map labels (T-031) -->'
if MB in t:
    t = t[:t.index(MB)] + t[t.index(ME):]
else:
    old = '  <img src="../../shared/map_mena_d1_overlay.svg" alt="">'
    assert t.count(old) == 1
    t = t.replace(old, '  <img src="../../screen4/A/map_overlay_cairo.svg" alt="">\n  ' + END.replace('/map labels', '/map labels (T-031)'))
    t = t.replace('url("../../shared/map_mena_d1_overlay.svg")', 'url("../../screen4/A/map_overlay_cairo.svg")')
    css_at = '  /* ---------- Device overlay (on top of the render, for the fit check) ---------- */'
    assert t.count(css_at) == 1
    t = t.replace(css_at, """  /* map names and city dots (T-031): an inline layer over the overlay's shapes; one a panel edge, the screen edge or the
     side inset would cut is hidden (cutLabels), so each is whole or fully under a panel */
  .map svg.labels { position: absolute; inset: 0; width: 100%; height: 100%; direction: ltr; }
  .labels .cut { display: none; }

""" + css_at)
    js_at = '  /* Frosted glass for the mockup render.'
    assert t.count(js_at) == 1
    t = t.replace(js_at, """  /* T-031: hide a map name (a city: its dot and name together) that a panel edge would cut (2 pt margin, halo included)
     or that the screen edge or the side inset would slice; one fully under a panel stays under its glass. */
  function cutLabels() {
    var d = window.__dev, W = d.W, H = d.H, sx = Math.max(d.SIDE, 0), M = 2;
    var obs = Array.prototype.filter.call(document.querySelectorAll('.hud .glass'), function (e) { return !e.classList.contains('menu') && e.getClientRects().length; })
      .map(function (e) { return e.getBoundingClientRect(); });
    var k = document.querySelector('.map').getBoundingClientRect().width / 1688, hidden = [];
    Array.prototype.forEach.call(document.querySelectorAll('.labels text'), function (t) {
      var key = t.getAttribute('data-city'), u = key === null ? [t] : [t, document.querySelector('.labels circle[data-city="' + key + '"]')];
      u.forEach(function (e) { e.classList.remove('cut'); });
      var b = u.map(function (e) { var r = e.getBoundingClientRect(), w = parseFloat(e.getAttribute('stroke-width') || 0) / 2 * k; return [r.left - w, r.top - w, r.right + w, r.bottom + w]; })
        .reduce(function (a, r) { return [Math.min(a[0], r[0]), Math.min(a[1], r[1]), Math.max(a[2], r[2]), Math.max(a[3], r[3])]; });
      if (b[2] <= 0 || b[0] >= W || b[3] <= 0 || b[1] >= H) return;                       /* off screen */
      var under = obs.some(function (o) { return b[0] >= o.left && b[2] <= o.right && b[1] >= o.top && b[3] <= o.bottom; });
      var cut = !under && obs.some(function (o) { return b[2] > o.left - M && b[0] < o.right + M && b[3] > o.top - M && b[1] < o.bottom + M; });
      var sliced = b[0] < sx || b[2] > W - sx || b[1] < 0 || b[3] > H;
      if (cut || sliced) { u.forEach(function (e) { e.classList.add('cut'); }); hidden.push(t.textContent); }
    });
    window.__map.hiddenLabels = hidden;
  }

""" + js_at)
    chain = '.then(fitTop).then(placeMap).then(frost)'
    assert t.count(chain) == 1
    t = t.replace(chain, '.then(fitTop).then(placeMap).then(cutLabels).then(frost)')
i = t.index(END.replace('/map labels', '/map labels (T-031)'))
t = t[:i] + MB + block[len(BEGIN):-len(END)] + t[i:]
PAGE.write_text(t, encoding='utf-8')
print('B3: label layer', block.count('<text'), 'names,', block.count('<circle'), 'city dots')
